        icon_data[canonical] = {}
        for variant_key, var_info in info['variants'].items():
            svg_file = ROOT / var_info['file']
            svg_text = svg_file.read_text(encoding='utf-8')
            icon_data[canonical][variant_key] = parse_svg_elements(svg_text)
            
