#!/usr/bin/env python3
"""Builds React source files from SVG sources and manifest.json.

Generates:
- packages/react/src/types.ts (Strongly typed icon names & variants)
- packages/react/src/data.ts (Parsed SVG nodes dictionary and aliases)
- packages/react/src/components/SolarIcon.tsx (React component with forwardRef)
- packages/react/src/index.ts (Package exports)
"""
from __future__ import annotations
import json
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PKG = ROOT / 'packages' / 'react'
SRC = PKG / 'src'
MANIFEST_FILE = ROOT / 'manifest.json'

def parse_svg_elements(svg_text: str):
    root = ET.fromstring(svg_text)
    elements = []
    
    def process_elem(elem):
        tag = elem.tag.rsplit('}', 1)[-1]
        if tag in ('defs', 'clipPath', 'svg'):
            return
        attrs = {}
        for k, v in elem.attrib.items():
            # Convert stroke-width, fill-rule, clip-rule to camelCase or preserve valid svg props
            attr_name = k.rsplit('}', 1)[-1]
            if attr_name == 'fill-rule':
                attrs['fillRule'] = v
            elif attr_name == 'clip-rule':
                attrs['clipRule'] = v
            elif attr_name == 'stroke-width':
                attrs['strokeWidth'] = v
            elif attr_name == 'stroke-linecap':
                attrs['strokeLinecap'] = v
            elif attr_name == 'stroke-linejoin':
                attrs['strokeLinejoin'] = v
            else:
                attrs[attr_name] = v
        elements.append([tag, attrs])

    for child in root:
        process_elem(child)
        for subchild in child:
            process_elem(subchild)

    return elements

def main():
    if not MANIFEST_FILE.is_file():
        print(f"Error: manifest.json not found at {MANIFEST_FILE}")
        sys.exit(1)
        
    SRC.mkdir(parents=True, exist_ok=True)
